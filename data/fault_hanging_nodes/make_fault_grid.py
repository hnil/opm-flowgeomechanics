# COORD/ZCORN for SIMPLE_MECH 11x11x25 with a vertical fault between rows J=JF and J=JF+1.
# Cells with J > JF are shifted down by THROW, so their corners hang on the other side's edges.
import sys
NX, NY, NZ = 11, 11, 25
DX, DY, DZ, TOP = 181.0, 181.0, 20.0, 1900.0
JF = int(sys.argv[1]) if len(sys.argv) > 1 else 8
THROW = float(sys.argv[2]) if len(sys.argv) > 2 else 10.0

def wrap(vals, n=6):
    return "\n".join(" ".join(vals[i:i+n]) for i in range(0, len(vals), n))

coord = []
for j in range(NY + 1):
    for i in range(NX + 1):
        x, y = i * DX, j * DY
        coord += [f"{x:g}", f"{y:g}", f"{TOP - 50:g}", f"{x:g}", f"{y:g}", f"{TOP + NZ * DZ + 50:g}"]

zcorn = []
for k in range(NZ):
    for top_bottom in (0, 1):
        for j in range(NY):
            for _ in (0, 1):
                for i in range(NX):
                    shift = THROW if j + 1 > JF else 0.0
                    z = TOP + (k + top_bottom) * DZ + shift
                    zcorn += [f"{z:g}", f"{z:g}"]

with open("FAULT_GRID.INC", "w") as f:
    f.write(f"-- generated by make_fault_grid.py JF={JF} THROW={THROW}\n")
    f.write("COORD\n" + wrap(coord) + "\n/\n\nZCORN\n" + wrap(zcorn, 8) + "\n/\n\n")
    f.write(f"FAULTS\n 'F1' 1 {NX} {JF} {JF} 1 {NZ} 'Y' /\n/\n")
